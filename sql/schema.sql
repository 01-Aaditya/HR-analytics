DROP TABLE IF EXISTS hr_attrition;

CREATE TABLE hr_attrition (
    age INTEGER,
    attrition TEXT,
    business_travel TEXT,
    daily_rate INTEGER,
    department TEXT,
    distance_from_home INTEGER,
    education INTEGER,
    education_field TEXT,
    employee_number INTEGER PRIMARY KEY,
    environment_satisfaction INTEGER,
    gender TEXT,
    hourly_rate INTEGER,
    job_involvement INTEGER,
    job_level INTEGER,
    job_role TEXT,
    job_satisfaction INTEGER,
    marital_status TEXT,
    monthly_income INTEGER,
    monthly_rate INTEGER,
    num_companies_worked INTEGER,
    over_time TEXT,
    percent_salary_hike INTEGER,
    performance_rating INTEGER,
    relationship_satisfaction INTEGER,
    stock_option_level INTEGER,
    total_working_years INTEGER,
    training_times_last_year INTEGER,
    work_life_balance INTEGER,
    years_at_company INTEGER,
    years_in_current_role INTEGER,
    years_since_last_promotion INTEGER,
    years_with_curr_manager INTEGER,
    attrition_flag INTEGER,
    retention_flag INTEGER,
    overtime_flag INTEGER,
    education_label TEXT,
    environment_satisfaction_label TEXT,
    job_satisfaction_label TEXT,
    relationship_satisfaction_label TEXT,
    work_life_balance_label TEXT,
    performance_rating_label TEXT,
    salary_band TEXT,
    tenure_band TEXT,
    experience_band TEXT,
    age_band TEXT,
    salary_to_level_ratio REAL,
    tenure_share_of_experience REAL
);
